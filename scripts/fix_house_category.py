def main():
    conn = mysql.connector.connect(**DB_CONFIG)
    cursor = conn.cursor()
    
    # 查询所有需要修正的数据
    cursor.execute("SELECT id, note FROM transaction WHERE category_id = 159")
    rows = cursor.fetchall()
    
    update_sql = "UPDATE transaction SET category_id = %s WHERE id = %s"
    
    stats = {}
    unmatched = []
    updated = 0
    
    for tid, note in rows:
        note_text = note or ""
        found = False
        for keyword, cat_id, cat_name in RULES:
            if keyword in note_text:
                cursor.execute(update_sql, (cat_id, tid))
                updated += 1
                stats[cat_name] = stats.get(cat_name, 0) + 1
                found = True
                break
        if not found:
            unmatched.append((tid, note_text))
    
    conn.commit()
    
    print(f"✅ 更新完成: {updated} 条")
    print(f"\n📊 分类分布:")
    for name, count in sorted(stats.items(), key=lambda x: -x[1]):
        print(f"  {name}: {count}条")
    
    if unmatched:
        print(f"\n⚠️ 未匹配 ({len(unmatched)}条):")
        for tid, note in unmatched:
            print(f"  ID={tid}: {note or '(无备注)'}")
    
    cursor.close()
    conn.close()

if __name__ == '__main__':
    main()
